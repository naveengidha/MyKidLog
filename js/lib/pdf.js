// pdf.js — jsPDF export helper

import { CATEGORY_LABELS } from '../data.js';

// hex → [r, g, b] for jsPDF
const CAT_COLORS = {
  gross:   [16,  185, 129],
  fine:    [245, 158,  11],
  cog:     [59,  130, 246],
  exec:    [139,  92, 246],
  comm:    [236,  72, 153],
  social:  [6,   182, 212],
  emo:     [249, 115,  22],
  sensory: [132, 204,  22],
  acad:    [99,  102, 241],
  create:  [217,  70, 239],
  life:    [20,  184, 166],
};

function fmtDur(m) {
  if (!m) return '0m';
  const h = Math.floor(m / 60), rem = m % 60;
  return h > 0 ? (rem > 0 ? `${h}h ${rem}m` : `${h}h`) : `${rem}m`;
}

export function exportPDF(days, profile, rangeLabel) {
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });

  const childName = profile.name || 'Child';
  const generated = new Date().toLocaleDateString('en-AU', { day:'numeric', month:'long', year:'numeric' });

  // ── Header ──
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text('Activity Log Report', 15, 20);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100);
  doc.text(`Child: ${childName}`, 15, 28);
  doc.text(`Period: ${rangeLabel}`, 15, 33);
  doc.text(`Generated: ${generated}`, 15, 38);

  // divider
  doc.setDrawColor(200);
  doc.line(15, 42, 195, 42);

  // ── Activity table ──
  const tableRows = [];
  const rowMeta   = []; // parallel array: primary category key per body row (null for section headers)
  const noteRows  = [];

  for (const day of days) {
    if (!day.activities.length && !day.dailyNote) continue;

    const dateLabel = new Date(day.date + 'T00:00:00').toLocaleDateString('en-AU', {
      weekday: 'short', day: 'numeric', month: 'short'
    });

    tableRows.push([{ content: dateLabel, colSpan: 5, styles: { fontStyle: 'bold', fillColor: [237, 233, 254], textColor: [79, 70, 229] } }]);
    rowMeta.push(null);

    if (day.activities.length) {
      day.activities.forEach(a => {
        const cats = (a.categories || []).map(c => CATEGORY_LABELS[c] || c).join(', ');
        const energy = a.energy ? `${a.energy}/5` : '—';
        tableRows.push([a.name, cats, fmtDur(a.duration), energy, a.note || '']);
        rowMeta.push((a.categories || [])[0] || null);
      });
    } else {
      tableRows.push([{ content: 'No activities logged', colSpan: 5, styles: { textColor: [150, 150, 150], fontStyle: 'italic' } }]);
      rowMeta.push(null);
    }

    if (day.dailyNote) {
      noteRows.push({ date: dateLabel, note: day.dailyNote });
    }
  }

  doc.autoTable({
    startY: 46,
    head: [['Activity', 'Categories', 'Duration', 'Energy', 'Note']],
    body: tableRows,
    styles: { fontSize: 9, cellPadding: 3 },
    headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: 'bold' },
    columnStyles: {
      0: { cellWidth: 44 },
      1: { cellWidth: 52 },
      2: { cellWidth: 20 },
      3: { cellWidth: 24, font: 'courier' },
      4: { cellWidth: 46 },
    },
    didParseCell(data) {
      if (data.section === 'body' && data.column.index === 1) {
        const catKey = rowMeta[data.row.index];
        if (catKey && CAT_COLORS[catKey]) {
          data.cell.styles.textColor = CAT_COLORS[catKey];
          data.cell.styles.fontStyle = 'bold';
        }
      }
    },
    margin: { left: 15, right: 15 },
  });

  // ── Daily notes section ──
  if (noteRows.length) {
    let y = doc.lastAutoTable.finalY + 10;
    if (y > 260) { doc.addPage(); y = 20; }

    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(30);
    doc.text('Daily Notes', 15, y);
    y += 6;

    doc.setDrawColor(200);
    doc.line(15, y, 195, y);
    y += 5;

    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');

    for (const row of noteRows) {
      if (y > 275) { doc.addPage(); y = 20; }
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(79, 70, 229);
      doc.text(row.date, 15, y);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(60);
      const lines = doc.splitTextToSize(row.note, 170);
      y += 5;
      doc.text(lines, 15, y);
      y += lines.length * 5 + 4;
    }
  }

  // ── Footer on each page ──
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(7);
    doc.setTextColor(160);
    doc.text(
      'Generated by KidLog — this is a parent-maintained activity record, not a clinical or diagnostic document.',
      15, 290
    );
    doc.text(`Page ${i} of ${pageCount}`, 185, 290, { align: 'right' });
  }

  doc.save(`KidLog-${childName.replace(/\s+/g,'-')}-${rangeLabel.replace(/[^a-zA-Z0-9]/g,'-')}.pdf`);
}
